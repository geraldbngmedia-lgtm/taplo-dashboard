export function swedishDateLabel(date = new Date()) {
  const weekdays = ["Söndag", "Måndag", "Tisdag", "Onsdag", "Torsdag", "Fredag", "Lördag"];
  const months = [
    "JAN.",
    "FEB.",
    "MARS",
    "APR.",
    "MAJ",
    "JUNI",
    "JULI",
    "AUG.",
    "SEP.",
    "OKT.",
    "NOV.",
    "DEC.",
  ];
  return `${weekdays[date.getDay()]} ${date.getDate()} ${months[date.getMonth()]}`.toUpperCase();
}
